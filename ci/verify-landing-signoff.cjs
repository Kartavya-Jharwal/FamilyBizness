const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/KJ/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = (process.env.MVP_QA_URL || 'http://127.0.0.1:4175/').replace(/\/?$/, '/');
const out = path.resolve('apps/portfolio/artifacts/landing-signoff');
fs.mkdirSync(out, { recursive: true });

(async () => {
  const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge', headless: true });
  const checks = [], errors = [], failedRequests = [];
  const context = await browser.newContext({ reducedMotion: 'reduce' });
  context.setDefaultTimeout(30000);
  context.setDefaultNavigationTimeout(60000);
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) failedRequests.push(`${response.status()} ${response.url()}`); });
  const check = (value, name) => { assert(value, name); checks.push(name); console.log(`PASS: ${name}`); };
  try {
    for (const width of [320, 390, 768, 1024, 1440, 1920]) {
      await page.setViewportSize({ width, height: 900 });
      const response = await page.goto(base, { waitUntil: 'networkidle' });
      check(response.ok(), `${width}: landing responds successfully`);
      await page.evaluate(() => document.fonts.ready);
      check(await page.locator('h1').count() === 1, `${width}: one page heading`);
      check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}: no horizontal overflow`);
      check((await page.locator('#family-office').boundingBox()).y >= 900, `${width}: capabilities below first viewport`);
      for (const image of await page.locator('img').all()) await image.scrollIntoViewIfNeeded();
      await page.locator('footer').scrollIntoViewIfNeeded();
      await page.waitForFunction(() => Array.from(document.images).every(image => image.complete));
      check(await page.evaluate(() => Array.from(document.images).every(image => image.naturalWidth > 0 && image.hasAttribute('alt'))), `${width}: images loaded with alt attributes`);
      await page.evaluate(() => scrollTo(0, 0));
      await page.screenshot({ path: path.join(out, `hero-${width}.png`), animations: 'disabled' });
      await page.screenshot({ path: path.join(out, `landing-${width}.png`), fullPage: true, animations: 'disabled' });
      await page.locator('#family-surname').fill('W'.repeat(60));
      check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}: long surname fits`);
      const header = await page.locator('.site-header').boundingBox();
      const eyebrow = await page.locator('.hero-eyebrow').boundingBox();
      check(header.y + header.height <= eyebrow.y, `${width}: header does not overlap hero`);
      await page.locator('#family-surname').fill('');
    }
    await page.goto(base);
    await page.keyboard.press('Tab');
    check(await page.locator('.skip-link').evaluate(el => el === document.activeElement), 'Keyboard starts on skip link');
    await page.keyboard.press('Enter');
    check(await page.locator('#main').evaluate(el => el === document.activeElement), 'Skip link focuses main content');
    await page.locator('#family-surname').fill('Audit Family');
    await page.reload();
    check(await page.locator('#family-surname').inputValue() === 'Audit Family', 'Surname persists after reload');
    check((await page.title()).includes('Audit Family Family Office'), 'Page title follows surname');
    const second = await context.newPage();
    await second.goto(base);
    await second.locator('#family-surname').fill('Cross Tab');
    await page.waitForFunction(() => document.querySelector('#family-surname').value === 'Cross Tab');
    check((await page.locator('.brand-mark').innerText()).includes('Cross Tab Family Office'), 'Surname brand synchronizes across tabs');
    check((await page.title()).includes('Cross Tab Family Office'), 'Surname title synchronizes across tabs');
    await second.close();
    await page.locator('#family-surname').fill('<img src=x onerror=alert(1)>');
    check(await page.locator('.brand-mark img').count() === 0, 'Surname rendered as text, never HTML');
    await page.locator('#family-surname').fill('');
    await page.getByRole('link', { name: "Let's log in" }).click();
    await page.getByRole('heading', { name: 'Who is visiting the family office?', exact: true }).waitFor();
    check(page.url().startsWith(base + 'portfolio/'), 'Login preserves deployment base path');
    await page.getByRole('button', { name: 'Open Family Patriarch', exact: true }).click();
    await page.getByRole('navigation', { name: 'Main navigation', exact: true }).waitFor();
    check(!new URL(page.url()).searchParams.has('choose-profile'), 'Patriarch enters prepared office');
    await page.goto(base + 'portfolio/#/settings/general');
    const settingsSurname = page.getByLabel('Family surname', { exact: true });
    await settingsSurname.fill('');
    await settingsSurname.pressSequentially('Van der Meer');
    await settingsSurname.press('Tab');
    check(await settingsSurname.inputValue() === 'Van der Meer', 'Settings accepts a surname typed with spaces');
    await page.goto(base);
    check((await page.locator('.brand-mark').innerText()).includes('Van der Meer Family Office'), 'Settings surname reaches landing');
    await page.locator('#family-surname').fill('Landing Review');
    await page.goto(base + 'portfolio/#/settings/general');
    check(await page.getByLabel('Family surname', { exact: true }).inputValue() === 'Landing Review', 'Landing surname reaches Settings');
    await page.goto(base);
    await page.getByRole('link', { name: "Let's log in" }).click();
    await page.getByRole('heading', { name: 'Who is visiting the family office?', exact: true }).waitFor();
    checks.push('Returning visitor still receives profile selection');
    const blocked = await browser.newContext();
    await blocked.addInitScript(() => { Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('Storage blocked', 'SecurityError'); } }); });
    const blockedPage = await blocked.newPage();
    await blockedPage.goto(base);
    await blockedPage.locator('#family-surname').fill('Private');
    check((await blockedPage.locator('.brand-mark').innerText()).includes('Private Family Office'), 'Surname remains editable when storage is blocked');
    await blocked.close();
    check(errors.length === 0, `No browser exceptions: ${errors.join('; ')}`);
    check(failedRequests.length === 0, `No failed HTTP responses: ${failedRequests.join('; ')}`);
    fs.writeFileSync(path.join(out, 'results.json'), JSON.stringify({ base, passed: true, checks, errors, failedRequests }, null, 2));
    console.log(`PASS: ${checks.length} landing and entry checks. Evidence: ${out}`);
  } catch (error) {
    await page.screenshot({ path: path.join(out, 'failure.png'), fullPage: true });
    fs.writeFileSync(path.join(out, 'results.json'), JSON.stringify({ base, passed: false, checks, failure: error.message, errors, failedRequests }, null, 2));
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
